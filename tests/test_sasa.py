# convergence
# --------------------------------------------------------------------------


def test_sasa_converges_as_points_increase(crambin):
    # Error against the independent FreeSASA total should shrink, in trend, as
    # the sampling gets finer. Checked as a trend rather than monotonically,
    # because individual point counts can land luckily.
    reference = compute_sasa(crambin, n_points=20000, reference=False).total
    counts = [16, 64, 256, 1024, 4096]
    errors = [
        abs(compute_sasa(crambin, n_points=n, reference=False).total - reference)
        / reference
        for n in counts
    ]
    assert errors[0] > errors[-1], errors
    assert errors[-1] < 2e-3, errors
    assert max(errors[2:]) < max(errors[:2]), errors


def test_coarse_sampling_is_still_the_right_order_of_magnitude(crambin):
    # Even 8 points per atom should not be wrong by a factor.
    reference = compute_sasa(crambin, n_points=4096, reference=False).total
    coarse = compute_sasa(crambin, n_points=8, reference=False).total
    assert 0.8 < coarse / reference < 1.2


def test_more_points_costs_nothing_in_correctness_for_isolated_atoms():
    radii = np.array([1.7])
    values = [
        sasa_from_arrays(np.zeros((1, 3)), radii, n_points=n)[0]
        for n in (3, 17, 256, 5000)
    ]
    assert len(set(round(v, 9) for v in values)) == 1


