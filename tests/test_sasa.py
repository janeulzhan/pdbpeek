def test_reference_file_describes_how_it_was_made(sasa_reference):
    assert sasa_reference["algorithm"] == "Shrake-Rupley"
    assert sasa_reference["generator"].startswith("freesasa ")
    assert sasa_reference["probe_radius"] == PROBE_RADIUS
    assert sasa_reference["entries"]


@pytest.mark.parametrize("entry", ["1CRN", "1UBQ", "2MBW", "4HHB"])
def test_total_sasa_matches_freesasa(entry, sasa_reference):
    # Relative differences measured on this machine at 1000 points were
    # 9.5e-4 (1CRN), 9.0e-4 (1UBQ), 2.6e-4 (2MBW) and 1.5e-4 (4HHB). The 1%
    # tolerance leaves an order of magnitude of headroom for a different
    # platform's libm.
    expected = sasa_reference["entries"][entry]
    selected = select(parse_file(cif_path(entry)))

    assert len(selected.atoms) == expected["n_atoms"]

    result = compute_sasa(selected, n_points=1000, reference=False)
    assert math.isclose(
        result.total, expected["total_sasa"], rel_tol=FREESASA_RTOL
    ), (entry, result.total, expected["total_sasa"])


def test_freesasa_agreement_is_tighter_than_the_asserted_tolerance(sasa_reference):
    # Guard against the tolerance above quietly becoming the thing that passes
    # the test. The worst entry should still be well inside it.
    worst = 0.0
    for entry, expected in sasa_reference["entries"].items():
        selected = select(parse_file(cif_path(entry)))
        total = compute_sasa(selected, n_points=1000, reference=False).total
        worst = max(worst, abs(total - expected["total_sasa"]) / expected["total_sasa"])
    assert worst < FREESASA_RTOL / 3.0, worst


