def test_empty_input_gives_empty_output():
    got = sasa_from_arrays(np.zeros((0, 3)), np.zeros(0))
    assert got.shape == (0,)
    assert got.sum() == 0.0


def test_mismatched_shapes_raise():
    with pytest.raises(ValueError, match="radii must be"):
        sasa_from_arrays(np.zeros((3, 3)), np.zeros(2))


@pytest.mark.parametrize("shape", [(3,), (3, 2), (3, 4), (2, 3, 3)])
def test_bad_coordinate_shape_raises(shape):
    with pytest.raises(ValueError, match=r"coords must be"):
        sasa_from_arrays(np.zeros(shape), np.zeros(3))


def test_probe_radius_changes_the_answer():
    coords = np.array([[0.0, 0.0, 0.0]])
    radii = np.array([1.7])
    dry = sasa_from_arrays(coords, radii, probe=0.0, n_points=64)[0]
    wet = sasa_from_arrays(coords, radii, probe=1.4, n_points=64)[0]
    assert math.isclose(dry, 4.0 * math.pi * 1.7**2, rel_tol=1e-12)
    assert wet > dry
