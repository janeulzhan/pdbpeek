def test_known_elements_use_the_bondi_table():
    assert radius_for("C") == 1.70
    assert radius_for("N") == 1.55
    assert radius_for("O") == 1.52
    assert radius_for("S") == 1.80
    assert radius_for(" c ") == 1.70, "lookup should be case and space tolerant"


def test_unknown_element_falls_back_and_is_reported():
    structure = select(parse_file(cif_path("1CRN")))
    # Swap one atom's element for something not in the table.
    from dataclasses import replace

    structure.atoms[0] = replace(structure.atoms[0], element="XX")
    result = compute_sasa(structure, n_points=64, reference=False)
    assert result.unknown_elements == ["XX"]
    assert radius_for("XX") == DEFAULT_RADIUS


def test_real_protein_has_no_unknown_elements(crambin):
    result = compute_sasa(crambin, n_points=64, reference=False)
    assert result.unknown_elements == []


