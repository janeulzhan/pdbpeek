def test_per_atom_areas_sum_to_the_total(crambin):
    result = compute_sasa(crambin, n_points=128, reference=False)
    assert result.atom_sasa.shape == (len(crambin.atoms),)
    assert math.isclose(result.atom_sasa.sum(), result.total, rel_tol=1e-12)


def test_residue_areas_sum_to_the_total(crambin):
    result = compute_sasa(crambin, n_points=128, reference=False)
    assert len(result.residue_keys) == 46
    assert math.isclose(result.residue_sasa.sum(), result.total, rel_tol=1e-12)


def test_no_atom_exceeds_its_own_isolated_sphere(crambin):
    result = compute_sasa(crambin, n_points=256, reference=False)
    ceiling = 4.0 * math.pi * (result.radii + result.probe) ** 2
    assert np.all(result.atom_sasa <= ceiling + 1e-9)
    assert np.all(result.atom_sasa >= 0.0)


def test_buried_atoms_exist_in_a_real_protein(crambin):
    result = compute_sasa(crambin, n_points=256, reference=False)
    assert (result.atom_sasa == 0.0).sum() > 0, "a folded protein has buried atoms"
    assert (result.atom_sasa > 0.0).sum() > 0


def test_relative_residue_sasa_is_a_sensible_fraction(crambin):
    result = compute_sasa(crambin, n_points=256, reference=True)
    rel = result.relative_residue_sasa
    assert rel is not None
    assert len(rel) == len(result.residue_keys)
    assert np.all(rel >= 0.0)
    # A residue's in-context area cannot exceed its isolated area by much. The
    # denominator ignores the neighbours that would otherwise occlude it, so
    # the ratio is bounded near 1 rather than exactly at it.
    assert rel.max() <= 1.05, rel.max()
    assert rel.min() < 0.1, "a folded protein has a deeply buried residue"


def test_reference_pass_is_optional(crambin):
    result = compute_sasa(crambin, n_points=64, reference=False)
    assert result.residue_reference is None
    assert result.relative_residue_sasa is None
    assert result.burial() is None


def test_burial_classification_splits_the_residues(crambin):
    result = compute_sasa(crambin, n_points=256, reference=True)
    burial = result.burial()
    assert burial is not None
    assert len(burial) == len(result.residue_keys)
    assert set(burial) == {"buried", "exposed"}


def test_burial_threshold_is_monotonic(crambin):
    result = compute_sasa(crambin, n_points=256, reference=True)
    counts = [
        result.burial(threshold=t).count("buried") for t in (0.0, 0.1, 0.25, 0.5, 1.0)
    ]
    assert counts == sorted(counts), counts
    assert counts[0] == 0
    assert counts[-1] == len(result.residue_keys)


def test_isolated_residue_reference_exceeds_in_context_area(crambin):
    result = compute_sasa(crambin, n_points=256, reference=True)
    assert result.residue_reference is not None
    # Removing neighbours can only expose more of a residue, so the reference
    # is an upper bound up to sampling noise.
    assert np.all(result.residue_sasa <= result.residue_reference * 1.05 + 1e-9)


def test_chain_removal_increases_exposure():
    # Pulling one haemoglobin chain out of the tetramer must expose the
    # surface that the other three were covering.
    raw = parse_file(cif_path("4HHB"))
    whole = compute_sasa(select(raw), n_points=128, reference=False)
    alone = compute_sasa(select(raw, chain="A"), n_points=128, reference=False)

    chain_a_in_context = sum(
        float(whole.residue_sasa[i])
        for i, key in enumerate(whole.residue_keys)
        if key[0] == "A"
    )
    assert alone.total > chain_a_in_context


